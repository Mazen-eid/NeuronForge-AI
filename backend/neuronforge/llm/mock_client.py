from __future__ import annotations

import json

from .base import LLMClient


class MockClient(LLMClient):
    """Deterministic stub used when no API key is configured. Produces valid JSON
    when asked (so the script generator keeps working in dry-run mode)."""

    async def complete(
        self,
        system: str,
        user: str,
        *,
        temperature: float = 0.7,
        max_tokens: int = 1200,
    ) -> str:
        lower = (system + "\n" + user).lower()
        if "json" in lower:
            return json.dumps(
                {
                    "title": "Sample Title (mock)",
                    "description": "A short, engaging description generated by the mock LLM.",
                    "hashtags": ["#sample", "#mock", "#neuronforge"],
                    "hook": "Did you know this one surprising fact?",
                    "narration": (
                        "This is a sample narration produced by the mock LLM. "
                        "Replace with a real provider (Groq, OpenAI, Ollama) to get real content. "
                        "The pipeline still runs end-to-end so you can verify TTS, video "
                        "assembly, and uploading work correctly."
                    ),
                    "captions": [
                        "This is a sample narration",
                        "produced by the mock LLM.",
                        "Replace with a real provider",
                        "to get real content.",
                    ],
                },
                ensure_ascii=False,
            )
        return "Mock response to: " + user[:120]
